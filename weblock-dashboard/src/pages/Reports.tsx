import React, { useState } from "react";
import { ApiError, api, type IncidentListItem } from "../api";
import { canWrite, useAuth } from "../auth";
import { EmptyState, ErrorState, Loading, QueryView, Section, useApi } from "../ui";

export function ReportsPage(): React.JSX.Element {
  const incidents = useApi(() => api.incidents({ limit: 100 }), []);
  const [selected, setSelected] = useState<number | null>(null);
  const [busy, setBusy] = useState<"json" | "pdf" | null>(null);
  const [message, setMessage] = useState<string | null>(null);
  const [nonce, setNonce] = useState(0);
  const { session } = useAuth();
  const latest = useApi(
    () =>
      selected === null
        ? Promise.resolve(null)
        : api.reportLatest(selected).catch((err: unknown) => {
            if (err instanceof ApiError && err.status === 404) return null;
            throw err;
          }),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [selected, nonce],
  );

  const exportReport = async (format: "json" | "pdf"): Promise<void> => {
    if (selected === null) return;
    setBusy(format);
    setMessage(null);
    try {
      const meta = await api.reportsExport(selected, format);
      setMessage(`Report v${meta.version} generated (${meta.sha256.slice(0, 16)}…).`);
      setNonce((n) => n + 1);
    } catch (err) {
      setMessage(err instanceof ApiError ? err.detail : "Export failed");
    } finally {
      setBusy(null);
    }
  };

  return (
    <div>
      <h1>Reports</h1>
      <p className="page-sub">Immutable versioned forensic reports, generated by the backend.</p>
      <Section title="Select incident">
        <QueryView state={incidents} emptyTitle="No incidents" emptyHint="Reports are per-incident.">
          {(list: IncidentListItem[]) => (
            <div className="field">
              <label htmlFor="rep-incident">Incident</label>
              <select
                id="rep-incident"
                value={selected ?? ""}
                onChange={(e) => setSelected(e.target.value ? Number(e.target.value) : null)}
              >
                <option value="">— choose —</option>
                {list.map((i) => (
                  <option key={i.id} value={i.id}>{i.incident_key} — {i.title}</option>
                ))}
              </select>
            </div>
          )}
        </QueryView>
      </Section>
      {selected !== null ? (
        <Section title="Latest report">
          {message ? <p role="status">{message}</p> : null}
          {latest.loading ? <Loading label="Report" /> :
            latest.error ? <ErrorState message={latest.error} onRetry={latest.reload} /> :
            !latest.data ? <EmptyState title="No reports yet" /> : (
              <ul className="kv-list">
                <li><span>Version</span><span>v{latest.data.version} ({latest.data.format.toUpperCase()})</span></li>
                <li><span>SHA-256</span><span className="mono small">{latest.data.sha256}</span></li>
                <li><span>Generated</span><span className="small">{latest.data.generated_at ?? "—"}</span></li>
              </ul>
            )}
          {canWrite(session?.role) ? (
            <div className="rowline" style={{ marginTop: 10 }}>
              <button type="button" className="btn btn-secondary" disabled={busy !== null} onClick={() => void exportReport("json")}>
                Generate JSON
              </button>
              <button type="button" className="btn btn-secondary" disabled={busy !== null} onClick={() => void exportReport("pdf")}>
                Generate PDF
              </button>
            </div>
          ) : null}
        </Section>
      ) : null}
    </div>
  );
}
